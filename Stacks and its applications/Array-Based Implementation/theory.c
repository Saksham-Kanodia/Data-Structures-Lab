/*Stacks are linear Data Structures that follow 
the LIFO (LAST IN, FIRST OUT) principle. This means the last inserted element is the one removed first.

Stack supports 2 primary operations:- 
1.) Push:- Inserts an element on top of the stack.
2.) Pop:- Removes the top element from the stack.

Other useful operations:-
1.) peek or top:- Returns the top element without removing it.
2.) isEmpty:- Check if the stack is empty.
3.) isFull:- Checks if the stack is Full (applicable for array based implementation).*/

